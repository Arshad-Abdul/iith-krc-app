// Simple helper to load active language from AsyncStorage or fallback to 'en'

export const getSavedLanguage = async () => {
  try {
    const lang = await AsyncStorage.getItem('krc_app_lang');
    return lang || 'en';
  } catch {
    return 'en';
  }
};

export const saveLanguageSetting = async (lang) => {
  try {
    await AsyncStorage.setItem('krc_app_lang', lang);
  } catch {}
};
